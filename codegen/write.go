package codegen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"sync/atomic"
)

func putGo(files map[string][]byte, rel, src string) error {
	if strings.TrimSpace(src) == "" {
		return nil
	}
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("codegen: format %s: %w\n%s", rel, err, src)
	}
	files[rel] = out
	return nil
}

// sameContent reports whether old, a file on disk, says what src does. Line
// endings are not what it says: a checkout with core.autocrlf -- the Windows
// default -- turns every LF into CRLF, and comparing bytes rewrote every
// generated file on every run and reported every one stale on every check.
// Both sides are normalised, because gqlc does not choose every file's
// endings: an SDL copy is written as its source is, so a CRLF source beside
// an LF checkout of the copy differed the other way round. A lone carriage
// return is not a line ending and still counts.
func sameContent(old, src []byte) bool {
	if bytes.Equal(old, src) {
		return true
	}
	crlf := []byte("\r\n")
	if !bytes.Contains(old, crlf) && !bytes.Contains(src, crlf) {
		return false
	}
	return bytes.Equal(bytes.ReplaceAll(old, crlf, []byte("\n")), bytes.ReplaceAll(src, crlf, []byte("\n")))
}

// writeGo writes src to path unless old, what the file held before this run,
// already says the same.
func writeGo(path string, old, src []byte) error {
	if old != nil && sameContent(old, src) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, src, 0o644)
}

// readExisting reads what path holds before a generate writes it, nil when it
// does not exist. A Go file there that does not carry the generator's header
// is somebody else's -- hand-written, or another generator's -- and is refused
// rather than replaced: prune has always read the header before deleting, and
// writing went straight over the same file.
func readExisting(path string) ([]byte, error) {
	old, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	// An empty file is nobody's work to lose: an interrupted generate leaves
	// one, and refusing it would block every generate after until someone
	// deleted it by hand.
	if strings.HasSuffix(path, ".go") && len(bytes.TrimSpace(old)) > 0 && !isGeneratedSource(old) {
		return nil, fmt.Errorf("codegen: %s exists and was not generated by gqlc (it does not open with %q); move it or choose another output directory", path, generatedMarker)
	}
	if old == nil {
		old = []byte{}
	}
	return old, nil
}

// ioParallel is how many files Generate opens at once, writing its output and
// reading headers to prune: enough to overlap Windows' per-open cost, few
// enough not to exhaust file handles.
const ioParallel = 16

// boundedEach calls fn for 0..n-1 on at most ioParallel goroutines, and
// waits. Workers take the next index as they finish: a goroutine per item,
// parked on a semaphore, was thousands of them at 800 groups for no more
// parallelism than this.
func boundedEach(n int, fn func(i int)) {
	var next atomic.Int64
	var wg sync.WaitGroup
	for range min(n, ioParallel) {
		wg.Go(func() {
			for {
				i := int(next.Add(1) - 1)
				if i >= n {
					return
				}
				fn(i)
			}
		})
	}
	wg.Wait()
}
