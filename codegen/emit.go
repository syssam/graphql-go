package codegen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/vektah/gqlparser/v2/ast"
)

func (b *builder) emit() (map[string][]byte, error) {
	files := map[string][]byte{}
	for _, src := range b.sources {
		base := filepath.Base(src.Name)
		files[filepath.ToSlash(filepath.Join("schema", base))] = []byte(src.Input)
	}
	groups := b.uniqueGroups()
	// Before anything is written: a name collision here would otherwise arrive
	// as a compile error in a file the author is told not to edit.
	if err := b.checkNameCollisions(groups); err != nil {
		return nil, err
	}
	// One model package per group keeps a one-group schema edit from
	// invalidating every other group's package. Input objects are the only
	// model types that can reference across groups, so a cycle among them
	// forces the single shared package instead.
	b.modelSplit = len(groups) > 1 && b.modelGroupsAcyclic(groups)
	if b.modelSplit {
		for _, g := range groups {
			src := b.emitModel(g)
			if src == "" {
				continue
			}
			if err := putGo(files, "model/"+g+"/models.go", src); err != nil {
				return nil, err
			}
		}
	} else if err := putGo(files, "model/models.go", b.emitModel("")); err != nil {
		return nil, err
	}
	if len(groups) <= 1 {
		if err := putGo(files, "generated.go", b.emitGroup(b.pkgName, "", true)); err != nil {
			return nil, err
		}
		if err := putGo(files, "schema.go", b.emitSchema()); err != nil {
			return nil, err
		}
		return files, nil
	}
	for _, g := range groups {
		if err := putGo(files, g+"/generated.go", b.emitGroup(g, g, b.hasResolver(g))); err != nil {
			return nil, err
		}
	}
	if err := putGo(files, "schema.go", b.emitSchemaGrouped(groups)); err != nil {
		return nil, err
	}
	return files, nil
}

func putGo(files map[string][]byte, rel, src string) error {
	if strings.TrimSpace(src) == "" {
		return nil
	}
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("codegen: format %s: %w\n%s", rel, err, src)
	}
	files[rel] = out
	return nil
}

func writeGo(path string, src []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	old, err := os.ReadFile(path)
	if err == nil && bytes.Equal(old, src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644)
}

const rootPkgDoc = "wires the generated GraphQL schema and its bindings."

// header renders a generated file's preamble. doc, when not empty, becomes
// the package comment: exactly one file per generated package carries one, so
// a consumer running a linter over code it cannot edit is not told to add a
// comment there, and go doc has something to show for the package.
func (b *builder) header(pkg, doc string) string {
	h := "// Code generated by gqlc. DO NOT EDIT.\n\n"
	if doc != "" {
		h += "// Package " + pkg + " " + doc + "\n"
	}
	return h + "package " + pkg + "\n\n"
}

// emitModel renders the model types of one group, or of the whole schema
// when group is empty.
func (b *builder) emitModel(group string) string {
	selfPkg := "model"
	if group != "" {
		selfPkg = group
	}
	var body strings.Builder
	for _, name := range b.typeNames(ast.Enum) {
		if !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " string\n\nconst (\n")
		for _, ev := range def.EnumValues {
			body.WriteString("\t" + name + goIdent(strings.ToLower(ev.Name)) + " " + name + " = \"" + ev.Name + "\"\n")
		}
		body.WriteString(")\n\n")
	}
	for _, name := range b.typeNames(ast.Scalar) {
		if _, ok := b.cfg.Models[name]; ok {
			continue
		}
		if !b.inGroup(name, group) {
			continue
		}
		body.WriteString("// " + name + " is a custom scalar; bind it with graphql.Scalar in NewSchema options.\n")
		body.WriteString("type " + name + " string\n\n")
	}
	for _, name := range b.typeNames(ast.Object) {
		if b.isRoot(name) || !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " struct {\n")
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") {
				continue
			}
			if b.fieldKind(name, fd) != fieldPure {
				continue
			}
			body.WriteString("\t" + goIdent(fd.Name) + " " + b.goType(fd.Type, selfPkg, false) + "\n")
		}
		body.WriteString("}\n\n")
	}
	for _, name := range b.typeNames(ast.InputObject) {
		if !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " struct {\n")
		for _, fd := range def.Fields {
			// The tag pins the SDL name. Deriving it back from the Go name is
			// lossy: an SDL field named ownerID becomes OwnerID, which derives
			// to ownerId, and the binding then fails to match the schema.
			body.WriteString("\t" + goIdent(fd.Name) + " " +
				b.goType(fd.Type, selfPkg, b.cfg.NullableInputOmittable) +
				" `graphql:\"" + fd.Name + "\"`\n")
		}
		body.WriteString("}\n\n")
	}
	s := body.String()
	if strings.TrimSpace(s) == "" {
		return ""
	}
	return b.header(selfPkg, "holds the types generated from the GraphQL schema.") + b.importBlock(s, selfPkg) + s
}

func (b *builder) emitArgs(group string) string {
	var body strings.Builder
	for _, name := range b.typeNames(ast.Object) {
		if !b.inGroup(name, group) {
			continue
		}
		def := b.schema.Types[name]
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") || len(fd.Arguments) == 0 {
				continue
			}
			body.WriteString("type " + b.argsName(name, fd.Name) + " struct {\n")
			for _, arg := range fd.Arguments {
				body.WriteString("\t" + goIdent(arg.Name) + " " + b.goType(arg.Type, "", false) + "\n")
			}
			body.WriteString("}\n\n")
		}
	}
	return body.String()
}

func (b *builder) importBlock(src, selfPkg string) string {
	var std, rest []string
	if strings.Contains(src, "context.") {
		std = append(std, "\t\"context\"")
	}
	if strings.Contains(src, "graphql.") {
		rest = append(rest, "\t\"github.com/syssam/graphql-go\"")
	}
	for qualifier, path := range b.modelExprImports() {
		if !strings.Contains(src, qualifier+".") {
			continue
		}
		line := "\t\"" + path + "\""
		if strings.Contains(path, ".") {
			rest = append(rest, line)
		} else {
			std = append(std, line)
		}
	}
	for _, pkg := range b.modelPkgNames() {
		if pkg == selfPkg {
			continue
		}
		if strings.Contains(src, pkg+".") {
			rest = append(rest, "\t\""+b.modelImportOf(pkg)+"\"")
		}
	}
	if len(std)+len(rest) == 0 {
		return ""
	}
	var out strings.Builder
	out.WriteString("import (\n")
	for _, l := range std {
		out.WriteString(l + "\n")
	}
	if len(std) > 0 && len(rest) > 0 {
		out.WriteString("\n")
	}
	for _, l := range rest {
		out.WriteString(l + "\n")
	}
	out.WriteString(")\n\n")
	return out.String()
}

// eachResolverField calls fn for every field of group that becomes a method on
// its Resolver interface. The collision check and the emitter share it, so the
// two cannot disagree about what the interface contains.
func (b *builder) eachResolverField(group string, fn func(typeName string, fd *ast.FieldDefinition)) {
	for _, name := range b.typeNames(ast.Object) {
		if !b.inGroup(name, group) {
			continue
		}
		for _, fd := range b.schema.Types[name].Fields {
			if strings.HasPrefix(fd.Name, "__") {
				continue
			}
			if b.fieldKind(name, fd) != fieldResolve {
				continue
			}
			// A method binding that can fail is still scheduled like a
			// resolver, but it is answered by the model, so asking the
			// Resolver interface for it would demand a method nothing calls.
			if fb, ok := b.manifest.binding(name, fd.Name); ok && fb.Kind != FieldResolver {
				continue
			}
			fn(name, fd)
		}
	}
}

func (b *builder) emitResolver(group string) string {
	var body strings.Builder
	body.WriteString("// Resolver holds methods for fields that are not struct data.\n")
	body.WriteString("type Resolver interface {\n")
	b.eachResolverField(group, func(name string, fd *ast.FieldDefinition) {
		{
			ret := b.goType(fd.Type, "", false)
			meth := b.resolverMethod(name, fd.Name)
			if b.isRoot(name) {
				if b.isSubscriptionRoot(name) {
					ret = "<-chan " + ret
				}
				if len(fd.Arguments) > 0 {
					fmt.Fprintf(&body, "\t%s(ctx context.Context, args %s) (%s, error)\n", meth, b.argsName(name, fd.Name), ret)
				} else {
					fmt.Fprintf(&body, "\t%s(ctx context.Context) (%s, error)\n", meth, ret)
				}
				return
			}
			parent := "*" + b.modelRef(name, name)
			if len(fd.Arguments) > 0 {
				fmt.Fprintf(&body, "\t%s(ctx context.Context, obj %s, args %s) (%s, error)\n", meth, parent, b.argsName(name, fd.Name), ret)
			} else {
				fmt.Fprintf(&body, "\t%s(ctx context.Context, obj %s) (%s, error)\n", meth, parent, ret)
			}
		}
	})
	body.WriteString("}\n")
	return body.String()
}

// checkNameCollisions refuses a schema whose generated names would collide.
//
// A Resolver method is its type name and field name run together, so two
// different fields can produce one name: FeatureFlag.targetingRules and
// FeatureFlagTargeting.rules are both FeatureFlagTargetingRules. Without this
// the generator emitted an interface with the method twice and the failure
// arrived as a compile error inside a file marked DO NOT EDIT, naming a line
// the author cannot act on.
//
// The interface and the args structs are per group, so a collision is only
// ever within one, and the cheapest fix is usually to move one of the two
// types to another SDL file rather than to rename a field.
func (b *builder) checkNameCollisions(groups []string) error {
	var errs []error
	report := func(kind, group, name, a, bcoord string) {
		errs = append(errs, fmt.Errorf(
			"codegen: %s in group %q: %s and %s both generate %q; "+
				"move one type to a different SDL file, or rename one of the fields",
			kind, group, a, bcoord, name))
	}
	for _, g := range groups {
		methods := map[string]string{}
		args := map[string]string{}
		b.eachResolverField(g, func(typeName string, fd *ast.FieldDefinition) {
			coord := typeName + "." + fd.Name
			if m := b.resolverMethod(typeName, fd.Name); methods[m] != "" {
				report("resolver method", g, m, methods[m], coord)
			} else {
				methods[m] = coord
			}
			if len(fd.Arguments) == 0 {
				return
			}
			if a := b.argsName(typeName, fd.Name); args[a] != "" {
				report("args struct", g, a, args[a], coord)
			} else {
				args[a] = coord
			}
		})
	}
	return errors.Join(errs...)
}

func (b *builder) emitBindings(group string, withResolver bool) string {
	var w strings.Builder
	if withResolver {
		w.WriteString("func Bindings(r Resolver) graphql.SchemaOption {\n\treturn graphql.Options(\n")
	} else {
		w.WriteString("func Bindings() graphql.SchemaOption {\n\treturn graphql.Options(\n")
	}

	for _, name := range b.typeNames(ast.Enum) {
		if !b.inGroup(name, group) {
			continue
		}
		def := b.schema.Types[name]
		w.WriteString("\t\tgraphql.Enum[" + b.modelRef(name, name) + "](\"" + name + "\", map[" + b.modelRef(name, name) + "]string{\n")
		for _, ev := range def.EnumValues {
			c := name + goIdent(strings.ToLower(ev.Name))
			w.WriteString("\t\t\t" + b.modelRef(name, c) + ": \"" + ev.Name + "\",\n")
		}
		w.WriteString("\t\t}),\n")
	}
	for _, name := range b.typeNames(ast.InputObject) {
		if !b.inGroup(name, group) {
			continue
		}
		w.WriteString("\t\tgraphql.Input[" + b.modelRef(name, name) + "](\"" + name + "\"),\n")
	}
	for _, name := range b.typeNames(ast.Interface) {
		if !b.inGroup(name, group) {
			continue
		}
		w.WriteString("\t\tgraphql.Interface[any](\"" + name + "\"),\n")
	}
	for _, name := range b.typeNames(ast.Union) {
		if !b.inGroup(name, group) {
			continue
		}
		w.WriteString("\t\tgraphql.Union[any](\"" + name + "\"),\n")
	}

	var rootFields = map[string][]string{}
	for _, name := range b.typeNames(ast.Object) {
		if !b.inGroup(name, group) {
			continue
		}
		if b.isRoot(name) {
			def := b.schema.Types[name]
			var calls []string
			for _, fd := range def.Fields {
				if strings.HasPrefix(fd.Name, "__") {
					continue
				}
				calls = append(calls, b.fieldCall(name, fd, true))
			}
			rootFields[name] = calls
			continue
		}
		def := b.schema.Types[name]
		w.WriteString("\t\tgraphql.Object[" + b.modelRef(name, name) + "](\"" + name + "\",\n")
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") {
				continue
			}
			w.WriteString(b.fieldCall(name, fd, false))
		}
		w.WriteString("\t\t),\n")
	}

	if q := b.schema.Query; q != nil && b.inGroup(q.Name, group) {
		w.WriteString("\t\tgraphql.Query(\n")
		for _, c := range rootFields[q.Name] {
			w.WriteString(c)
		}
		w.WriteString("\t\t),\n")
	}
	if m := b.schema.Mutation; m != nil && b.inGroup(m.Name, group) {
		w.WriteString("\t\tgraphql.Mutation(\n")
		for _, c := range rootFields[m.Name] {
			w.WriteString(c)
		}
		w.WriteString("\t\t),\n")
	}
	if s := b.schema.Subscription; s != nil && b.inGroup(s.Name, group) {
		w.WriteString("\t\tgraphql.Subscription(\n")
		for _, c := range rootFields[s.Name] {
			w.WriteString(c)
		}
		w.WriteString("\t\t),\n")
	}

	seen := map[string]bool{}
	for _, name := range b.typeNames(ast.Object) {
		if !b.inGroup(name, group) {
			continue
		}
		def := b.schema.Types[name]
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") || len(fd.Arguments) == 0 {
				continue
			}
			an := b.argsName(name, fd.Name)
			if seen[an] {
				continue
			}
			seen[an] = true
			w.WriteString("\t\tgraphql.Args[" + an + "](),\n")
		}
	}

	w.WriteString("\t)\n}\n")
	return w.String()
}

func (b *builder) fieldCall(typeName string, fd *ast.FieldDefinition, root bool) string {
	goRet := b.goType(fd.Type, "", false)
	if fb, ok := b.manifest.binding(typeName, fd.Name); ok && fb.Kind != FieldResolver {
		return b.manifestFieldCall(typeName, fd, fb, goRet)
	}
	switch {
	case b.isSubscriptionRoot(typeName):
		meth := b.resolverMethod(typeName, fd.Name)
		if len(fd.Arguments) > 0 {
			an := b.argsName(typeName, fd.Name)
			return fmt.Sprintf("\t\t\tgraphql.SubscribeArgs(%q, func(ctx context.Context, a %s) (<-chan %s, error) { return r.%s(ctx, a) }),\n", fd.Name, an, goRet, meth)
		}
		return fmt.Sprintf("\t\t\tgraphql.Subscribe(%q, func(ctx context.Context) (<-chan %s, error) { return r.%s(ctx) }),\n", fd.Name, goRet, meth)
	case b.fieldKind(typeName, fd) == fieldPure:
		recv := "*" + b.modelRef(typeName, typeName)
		ident := goIdent(fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Field(%q, func(v %s) %s { return v.%s }),\n", fd.Name, recv, goRet, ident)
	case len(fd.Arguments) > 0 && root:
		an := b.argsName(typeName, fd.Name)
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.ResolveArgs(%q, func(ctx context.Context, _ graphql.Root, a %s) (%s, error) { return r.%s(ctx, a) }),\n", fd.Name, an, goRet, meth)
	case len(fd.Arguments) > 0:
		an := b.argsName(typeName, fd.Name)
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.ResolveArgs(%q, func(ctx context.Context, v *%s, a %s) (%s, error) { return r.%s(ctx, v, a) }),\n", fd.Name, b.modelRef(typeName, typeName), an, goRet, meth)
	case root:
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Resolve(%q, func(ctx context.Context, _ graphql.Root) (%s, error) { return r.%s(ctx) }),\n", fd.Name, goRet, meth)
	default:
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Resolve(%q, func(ctx context.Context, v *%s) (%s, error) { return r.%s(ctx, v) }),\n", fd.Name, b.modelRef(typeName, typeName), goRet, meth)
	}
}

func (b *builder) emitSchema() string {
	var w strings.Builder
	w.WriteString(b.header(b.pkgName, rootPkgDoc))
	w.WriteString(`import (
	"embed"

	"github.com/syssam/graphql-go"
)

//go:embed schema/*.graphql
var sdl embed.FS

func NewSchema(r Resolver, opts ...graphql.SchemaOption) (*graphql.Schema, error) {
	all := append([]graphql.SchemaOption{Bindings(r)}, opts...)
	return graphql.NewSchema(graphql.SDLFS(sdl, "schema/*.graphql"), all...)
}
`)
	return w.String()
}

func (b *builder) emitSchemaGrouped(groups []string) string {
	var w strings.Builder
	w.WriteString(b.header(b.pkgName, rootPkgDoc))
	w.WriteString("import (\n\t\"embed\"\n\n\t\"github.com/syssam/graphql-go\"\n")
	for _, g := range groups {
		w.WriteString("\t\"" + b.cfg.Package + "/" + g + "\"\n")
	}
	w.WriteString(")\n\n")
	w.WriteString("//go:embed schema/*.graphql\nvar sdl embed.FS\n\n")
	w.WriteString("type Resolvers struct {\n")
	for _, g := range groups {
		if b.hasResolver(g) {
			w.WriteString("\t" + groupField(g) + " " + g + ".Resolver\n")
		}
	}
	w.WriteString("}\n\n")
	w.WriteString("func NewSchema(r Resolvers, opts ...graphql.SchemaOption) (*graphql.Schema, error) {\n")
	w.WriteString("\tall := []graphql.SchemaOption{\n")
	for _, g := range groups {
		if b.hasResolver(g) {
			w.WriteString("\t\t" + g + ".Bindings(r." + groupField(g) + "),\n")
		} else {
			w.WriteString("\t\t" + g + ".Bindings(),\n")
		}
	}
	w.WriteString("\t}\n")
	w.WriteString("\tall = append(all, opts...)\n")
	w.WriteString("\treturn graphql.NewSchema(graphql.SDLFS(sdl, \"schema/*.graphql\"), all...)\n}\n")
	return w.String()
}

// emitGroup renders one group as a single file. Args, the Resolver interface
// and the bindings all live in the same package, so splitting them across
// three files only multiplied the file count: what the compiler rebuilds is
// decided by the package, not the file.
func (b *builder) emitGroup(pkg, group string, withResolver bool) string {
	parts := []string{b.emitArgs(group)}
	if withResolver {
		parts = append(parts, b.emitResolver(group))
	}
	parts = append(parts, b.emitBindings(group, withResolver))

	var body strings.Builder
	for _, p := range parts {
		if strings.TrimSpace(p) == "" {
			continue
		}
		body.WriteString(p)
		if !strings.HasSuffix(p, "\n\n") {
			body.WriteString("\n")
		}
	}
	s := body.String()
	if strings.TrimSpace(s) == "" {
		return ""
	}
	doc := ""
	if pkg != b.pkgName {
		doc = "holds the generated GraphQL bindings for the " + group + " group."
	}
	return b.header(pkg, doc) + b.importBlock(s, "") + s
}
