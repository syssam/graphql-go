func (b *builder) emit() (map[string][]byte, error) {
	b.reportUnboundScalars()
	files := map[string][]byte{}
	for _, src := range b.sources {
		base := filepath.Base(src.Name)
		files[filepath.ToSlash(filepath.Join("schema", base))] = []byte(src.Input)
	}
	groups := b.uniqueGroups()
	// Before anything is written: a name collision here would otherwise arrive
	// as a compile error in a file the author is told not to edit.
	if err := errors.Join(b.checkNameCollisions(groups), b.checkIdentifiers()); err != nil {
		return nil, err
	}
	// One model package per group keeps a one-group schema edit from
	// invalidating every other group's package. Input objects are the only
	// model types that can reference across groups, so a cycle among them
	// forces the single shared package instead.
	b.modelSplit = len(groups) > 1 && b.modelGroupsAcyclic(groups)
	if b.modelSplit {
		for _, g := range groups {
			src := b.emitModel(g)
			if src == "" {
				continue
			}
			if err := putGo(files, "model/"+g+"/models.go", src); err != nil {
				return nil, err
			}
		}
	} else if err := putGo(files, "model/models.go", b.emitModel("")); err != nil {
		return nil, err
	}
	if len(groups) <= 1 {
		if err := putGo(files, "generated.go", b.emitGroup(b.pkgName, "", true)); err != nil {
			return nil, err
		}
		if err := putGo(files, "schema.go", b.emitSchema()); err != nil {
			return nil, err
		}
		return files, nil
	}
	for _, g := range groups {
		if err := putGo(files, g+"/generated.go", b.emitGroup(g, g, b.hasResolver(g))); err != nil {
			return nil, err
		}
	}
	if err := putGo(files, "schema.go", b.emitSchemaGrouped(groups)); err != nil {
		return nil, err
	}
	return files, nil
}

func putGo(files map[string][]byte, rel, src string) error {
	if strings.TrimSpace(src) == "" {
		return nil
	}
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("codegen: format %s: %w\n%s", rel, err, src)
	}
	files[rel] = out
	return nil
}

func writeGo(path string, src []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	old, err := os.ReadFile(path)
	if err == nil && bytes.Equal(old, src) {
		return nil
	}
	return os.WriteFile(path, src, 0o644)
}

const rootPkgDoc = "wires the generated GraphQL schema and its bindings."

// header renders a generated file's preamble. doc, when not empty, becomes
// the package comment: exactly one file per generated package carries one, so
// a consumer running a linter over code it cannot edit is not told to add a
// comment there, and go doc has something to show for the package.
func (b *builder) header(pkg, doc string) string {
	h := "// Code generated by gqlc. DO NOT EDIT.\n\n"
	if doc != "" {
		h += "// Package " + pkg + " " + doc + "\n"
	}
	return h + "package " + pkg + "\n\n"
}

// emitModel renders the model types of one group, or of the whole schema
// when group is empty.
func (b *builder) emitModel(group string) string {
	selfPkg := "model"
	if group != "" {
		selfPkg = group
	}
	var body strings.Builder
	for _, name := range b.typeNames(ast.Enum) {
		if !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " string\n\nconst (\n")
		for _, ev := range def.EnumValues {
			body.WriteString("\t" + name + goIdent(strings.ToLower(ev.Name)) + " " + name + " = \"" + ev.Name + "\"\n")
		}
		body.WriteString(")\n\n")
	}
	for _, name := range b.typeNames(ast.Scalar) {
		if _, ok := b.cfg.Models[name]; ok {
			continue
		}
		if !b.inGroup(name, group) {
			continue
		}
		body.WriteString("// " + name + " is a custom scalar; bind it with graphql.Scalar in NewSchema options.\n")
		body.WriteString("type " + name + " string\n\n")
	}
	for _, kind := range []ast.DefinitionKind{ast.Interface, ast.Union} {
		for _, name := range b.typeNames(kind) {
			if !b.inGroup(name, group) || !b.hasMarker(name) {
				continue
			}
			body.WriteString("type " + name + " interface {\n")
			for _, m := range b.markerMethods(name) {
				body.WriteString("\t" + m + "()\n")
			}
			body.WriteString("}\n\n")
		}
	}
	for _, name := range b.typeNames(ast.Object) {
		if b.isRoot(name) || !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " struct {\n")
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") {
				continue
			}
			if b.fieldKind(name, fd) != fieldPure {
				continue
			}
			body.WriteString("\t" + goIdent(fd.Name) + " " + b.goType(fd.Type, selfPkg, false) + "\n")
		}
		body.WriteString("}\n\n")
		for _, abstract := range b.markersOf(name) {
			body.WriteString("func (*" + name + ") " + b.markerMethod(abstract) + "() {}\n\n")
		}
	}
	for _, name := range b.typeNames(ast.InputObject) {
		if !b.inGroup(name, group) || b.mapped(name) {
			continue
		}
		def := b.schema.Types[name]
		body.WriteString("type " + name + " struct {\n")
		for _, fd := range def.Fields {
			// The tag pins the SDL name. Deriving it back from the Go name is
			// lossy: an SDL field named ownerID becomes OwnerID, which derives
			// to ownerId, and the binding then fails to match the schema.
			body.WriteString("\t" + goIdent(fd.Name) + " " +
				b.goType(fd.Type, selfPkg, b.cfg.NullableInputOmittable) +
				" `graphql:\"" + fd.Name + "\"`\n")
		}
		body.WriteString("}\n\n")
	}
	s := body.String()
	if strings.TrimSpace(s) == "" {
		return ""
	}
	return b.header(selfPkg, "holds the types generated from the GraphQL schema.") + b.importBlock(s, selfPkg) + s
}

func (b *builder) emitArgs(group string) string {
	var body strings.Builder
	b.eachGroupField(group, func(name string, fd *ast.FieldDefinition) {
		if len(fd.Arguments) == 0 {
			return
		}
		body.WriteString("type " + b.argsName(name, fd.Name) + " struct {\n")
		for _, arg := range fd.Arguments {
			// The tag pins the SDL name, for the reason the input-object
			// emitter above gives: deriving it back from the Go name is
			// lossy. Args structs went without one until an SDL argument
			// arrived that does not survive the round trip -- ownerID
			// derives to ownerId, and _lastUpdatedAt to xLastUpdatedAt.
			body.WriteString("\t" + goIdent(arg.Name) + " " +
				b.goType(arg.Type, "", false) +
				" `graphql:\"" + arg.Name + "\"`\n")
		}
		body.WriteString("}\n\n")
	})
	return body.String()
}

func (b *builder) importBlock(src, selfPkg string) string {
	used := usedQualifiers(src)
	var std, rest []string
	if used("context") {
		std = append(std, "\t\"context\"")
	}
	if used("graphql") {
		rest = append(rest, "\t\"github.com/syssam/graphql-go\"")
	}
	for qualifier, path := range b.modelExprImports() {
		if !used(qualifier) {
			continue
		}
		// Always aliased: modelExprImports chose the qualifier without knowing
		// the package's own name, which need not be its directory's.
		line := "\t\"" + path + "\""
		if path != qualifier {
			line = "\t" + qualifier + " \"" + path + "\""
		}
		if strings.Contains(path, ".") {
			rest = append(rest, line)
		} else {
			std = append(std, line)
		}
	}
	// An extra enum's package is named by neither Config.Models nor the
	// generated models, and its qualifier was settled in setExtraEnums, so
	// the import is written under that name whenever it differs from the
	// package's own.
	for _, qualifier := range slices.Sorted(maps.Keys(b.extraImports)) {
		if !used(qualifier) {
			continue
		}
		path := b.extraImports[qualifier]
		if base := path[strings.LastIndex(path, "/")+1:]; base == qualifier {
			rest = append(rest, "\t\""+path+"\"")
			continue
		}
		rest = append(rest, "\t"+qualifier+" \""+path+"\"")
	}
	for _, pkg := range b.modelPkgNames() {
		if pkg == selfPkg {
			continue
		}
		// The qualifier, not the package name: a generated model package whose
		// name is taken by a mapped type's package is referred to, and so
		// imported, under an alias. See modelQualifier.
		q := b.modelQualifier(pkg)
		if !used(q) {
			continue
		}
		if q == pkg {
			rest = append(rest, "\t\""+b.modelImportOf(pkg)+"\"")
			continue
		}
		rest = append(rest, "\t"+q+" \""+b.modelImportOf(pkg)+"\"")
	}
	if len(std)+len(rest) == 0 {
		return ""
	}
	var out strings.Builder
	out.WriteString("import (\n")
	for _, l := range std {
		out.WriteString(l + "\n")
	}
	if len(std) > 0 && len(rest) > 0 {
		out.WriteString("\n")
	}
	for _, l := range rest {
		out.WriteString(l + "\n")
	}
	out.WriteString(")\n\n")
	return out.String()
}

// eachResolverField calls fn for every field of group that becomes a method on
// its Resolver interface. The collision check and the emitter share it, so the
// two cannot disagree about what the interface contains.
func (b *builder) eachResolverField(group string, fn func(typeName string, fd *ast.FieldDefinition)) {
	b.eachGroupField(group, func(name string, fd *ast.FieldDefinition) {
		if b.fieldKind(name, fd) != fieldResolve {
			return
		}
		// A method binding that can fail is still scheduled like a
		// resolver, but it is answered by the model, so asking the
		// Resolver interface for it would demand a method nothing calls.
		if _, ok := b.modelAnswers(name, fd); ok {
			return
		}
		fn(name, fd)
	})
}

func (b *builder) emitResolver(group string) string {
	var body strings.Builder
	body.WriteString("// Resolver holds methods for fields that are not struct data.\n")
	body.WriteString("type Resolver interface {\n")
	for _, m := range b.resolverSignatures(group, "") {
		fmt.Fprintf(&body, "\t%s%s\n", m.name, m.signature)
	}
	body.WriteString("}\n")
	return body.String()
}

// resolverSig is one method of a group's Resolver interface.
type resolverSig struct {
	name      string
	signature string // "(ctx context.Context, args XArgs) (T, error)"
	coord     string // "Query.products", for messages and stub comments
	doc       string // the field's SDL description
}

// resolverSignatures renders the group's Resolver methods. The interface
// and the scaffolded stubs both come from here, so a stub always has the
// signature the interface asks for. argsQual qualifies the args structs,
// which live in the group package: empty inside it, "productgql." outside.
func (b *builder) resolverSignatures(group, argsQual string) []resolverSig {
	var out []resolverSig
	b.eachResolverField(group, func(name string, fd *ast.FieldDefinition) {
		ret := b.goType(fd.Type, "", false)
		args := ""
		if len(fd.Arguments) > 0 {
			args = ", args " + argsQual + b.argsName(name, fd.Name)
		}
		var sig string
		switch {
		case b.isRoot(name):
			if b.isSubscriptionRoot(name) {
				ret = "<-chan " + ret
			}
			sig = fmt.Sprintf("(ctx context.Context%s) (%s, error)", args, ret)
		default:
			sig = fmt.Sprintf("(ctx context.Context, obj *%s%s) (%s, error)", b.modelRef(name, name), args, ret)
		}
		out = append(out, resolverSig{
			name:      b.resolverMethod(name, fd.Name),
			signature: sig,
			coord:     name + "." + fd.Name,
			doc:       fd.Description,
		})
	})
	return out
}

// checkNameCollisions refuses a schema whose generated names would collide.
//
// A Resolver method is its type name and field name run together, so two
// different fields can produce one name: FeatureFlag.targetingRules and
// FeatureFlagTargeting.rules are both FeatureFlagTargetingRules. Without this
// the generator emitted an interface with the method twice and the failure
// arrived as a compile error inside a file marked DO NOT EDIT, naming a line
// the author cannot act on.
//
// The interface and the args structs are per group, so a collision is only
// ever within one, and the cheapest fix is usually to move one of the two
// types to another SDL file rather than to rename a field.
func (b *builder) checkNameCollisions(groups []string) error {
	var errs []error
	report := func(kind, group, name, a, bcoord string) {
		errs = append(errs, fmt.Errorf(
			"codegen: %s in group %q: %s and %s both generate %q; "+
				"move one type to a different SDL file, or rename one of the fields",
			kind, group, a, bcoord, name))
	}
	for _, g := range groups {
		methods := map[string]string{}
		args := map[string]string{}
		b.eachResolverField(g, func(typeName string, fd *ast.FieldDefinition) {
			coord := typeName + "." + fd.Name
			if m := b.resolverMethod(typeName, fd.Name); methods[m] != "" {
				report("resolver method", g, m, methods[m], coord)
			} else {
				methods[m] = coord
			}
			if len(fd.Arguments) == 0 {
				return
			}
			if a := b.argsName(typeName, fd.Name); args[a] != "" {
				report("args struct", g, a, args[a], coord)
			} else {
				args[a] = coord
			}
		})
	}
	return errors.Join(errs...)
}

// abstractRef is the Go type an interface or union is bound to: its marker
// when it has one. A mapped abstract type stays bound to any, as it always
// was: the executor resolves it from the dynamic type either way.
func (b *builder) abstractRef(name string) string {
	if b.hasMarker(name) {
		return b.modelRef(name, name)
	}
	return "any"
}

// markersOf lists the abstract types with a marker that object belongs to, in
// name order so the output is stable.
func (b *builder) markersOf(object string) []string {
	var out []string
	for _, kind := range []ast.DefinitionKind{ast.Interface, ast.Union} {
		for _, name := range b.typeNames(kind) {
			if !b.hasMarker(name) {
				continue
			}
			for _, member := range b.schema.PossibleTypes[name] {
				if member.Name == object {
					out = append(out, name)
					break
				}
			}
		}
	}
	return out
}

// checkIdentifiers refuses legal SDL whose generated Go would not compile.
// GraphQL names are case-sensitive and Go identifiers are derived from them
// by goIdent, which folds: id and ID are both ID, userId and userID both
// UserID, and the enum values Low and LOW both end in Low. A type is emitted
// under its SDL name, so a type named in lower case is unexported and the
// bindings cannot name it. Each of these used to be written out and fail as a
// compile error in a DO NOT EDIT file; renaming them silently instead would
// make the Go name unguessable from the schema.
func (b *builder) checkIdentifiers() error {
	var errs []error
	fold := func(kind string) func(ident, coord string) {
		seen := map[string]string{}
		return func(ident, coord string) {
			if prev, ok := seen[ident]; ok {
				errs = append(errs, fmt.Errorf(
					"codegen: %s %s and %s both generate the Go name %q; rename one of them in the schema",
					kind, prev, coord, ident))
				return
			}
			seen[ident] = coord
		}
	}
	exported := func(name string) {
		if r, _ := utf8.DecodeRuneInString(name); !unicode.IsUpper(r) {
			errs = append(errs, fmt.Errorf(
				"codegen: type %q would generate an unexported Go type; rename it, or bind it to an existing Go type with Config.Models",
				name))
		}
	}

	for _, name := range b.typeNames(ast.Enum) {
		if b.mapped(name) {
			continue
		}
		exported(name)
		add := fold("enum values")
		for _, ev := range b.schema.Types[name].EnumValues {
			add(name+goIdent(strings.ToLower(ev.Name)), name+"."+ev.Name)
		}
	}
	for _, name := range b.typeNames(ast.Scalar) {
		if !b.mapped(name) {
			exported(name)
		}
	}
	for _, name := range b.typeNames(ast.Object) {
		def := b.schema.Types[name]
		if !b.isRoot(name) && !b.mapped(name) {
			exported(name)
			add := fold("fields")
			for _, fd := range def.Fields {
				if !strings.HasPrefix(fd.Name, "__") && b.fieldKind(name, fd) == fieldPure {
					add(goIdent(fd.Name), name+"."+fd.Name)
				}
			}
		}
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") || len(fd.Arguments) == 0 {
				continue
			}
			add := fold("arguments")
			for _, arg := range fd.Arguments {
				add(goIdent(arg.Name), name+"."+fd.Name+"("+arg.Name+":)")
			}
		}
	}
	for _, name := range b.typeNames(ast.InputObject) {
		if b.mapped(name) {
			continue
		}
		exported(name)
		add := fold("input fields")
		for _, fd := range b.schema.Types[name].Fields {
			add(goIdent(fd.Name), name+"."+fd.Name)
		}
	}
	return errors.Join(errs...)
}

func (b *builder) emitBindings(group string, withResolver bool) string {
	var w strings.Builder
	if withResolver {
		w.WriteString("func Bindings(r Resolver) graphql.SchemaOption {\n\treturn graphql.Options(\n")
	} else {
		w.WriteString("func Bindings() graphql.SchemaOption {\n\treturn graphql.Options(\n")
	}

	for _, name := range b.typeNames(ast.Enum) {
		if !b.inGroup(name, group) {
			continue
		}
		def := b.schema.Types[name]
		w.WriteString("\t\tgraphql.Enum[" + b.modelRef(name, name) + "](\"" + name + "\", map[" + b.modelRef(name, name) + "]string{\n")
		for _, ev := range def.EnumValues {
			c, declared := b.manifest.enumConstant(name, ev.Name)
			if !declared {
				c = name + goIdent(strings.ToLower(ev.Name))
			}
			w.WriteString("\t\t\t" + b.modelRef(name, c) + ": \"" + ev.Name + "\",\n")
		}
		w.WriteString("\t\t}),\n")
		// A second Go type for the same enum. The registry is keyed on
		// (GraphQL type, reflect.Type), so both bindings live at once and each
		// position decodes into the type it actually holds.
		for _, e := range b.extraEnums[name] {
			w.WriteString("\t\tgraphql.Enum[" + e.ref + "](\"" + name + "\", map[" + e.ref + "]string{\n")
			for _, ev := range def.EnumValues {
				w.WriteString("\t\t\t" + e.consts[ev.Name] + ": \"" + ev.Name + "\",\n")
			}
			w.WriteString("\t\t}),\n")
		}
	}
	for _, name := range b.typeNames(ast.InputObject) {
		if !b.inGroup(name, group) {
			continue
		}
		opt := ""
		if b.cfg.ZeroForNullInputs {
			opt = ", graphql.ZeroForNull()"
		}
		w.WriteString("\t\tgraphql.Input[" + b.modelRef(name, name) + "](\"" + name + "\"" + opt + "),\n")
	}
	for _, name := range b.typeNames(ast.Interface) {
		if !b.inGroup(name, group) {
			continue
		}
		w.WriteString("\t\tgraphql.Interface[" + b.abstractRef(name) + "](\"" + name + "\"),\n")
	}
	for _, name := range b.typeNames(ast.Union) {
		if !b.inGroup(name, group) {
			continue
		}
		w.WriteString("\t\tgraphql.Union[" + b.abstractRef(name) + "](\"" + name + "\"),\n")
	}

	var rootFields = map[string][]string{}
	for _, name := range b.typeNames(ast.Object) {
		if b.isRoot(name) {
			for _, fd := range b.schema.Types[name].Fields {
				if strings.HasPrefix(fd.Name, "__") || !b.fieldInGroup(name, fd, group) {
					continue
				}
				rootFields[name] = append(rootFields[name], b.fieldCall(name, fd, true))
			}
			continue
		}
		if !b.inGroup(name, group) {
			continue
		}
		def := b.schema.Types[name]
		w.WriteString("\t\tgraphql.Object[" + b.modelRef(name, name) + "](\"" + name + "\",\n")
		for _, fd := range def.Fields {
			if strings.HasPrefix(fd.Name, "__") {
				continue
			}
			w.WriteString(b.fieldCall(name, fd, false))
		}
		w.WriteString("\t\t),\n")
	}

	// Each group binds only its own root fields; the engine merges the
	// several Query calls this makes across groups into one root.
	for _, root := range []struct {
		def  *ast.Definition
		call string
	}{{b.schema.Query, "Query"}, {b.schema.Mutation, "Mutation"}, {b.schema.Subscription, "Subscription"}} {
		if root.def == nil || len(rootFields[root.def.Name]) == 0 {
			continue
		}
		w.WriteString("\t\tgraphql." + root.call + "(\n")
		for _, c := range rootFields[root.def.Name] {
			w.WriteString(c)
		}
		w.WriteString("\t\t),\n")
	}

	seen := map[string]bool{}
	b.eachGroupField(group, func(name string, fd *ast.FieldDefinition) {
		if len(fd.Arguments) == 0 {
			return
		}
		an := b.argsName(name, fd.Name)
		if seen[an] {
			return
		}
		seen[an] = true
		w.WriteString("\t\tgraphql.Args[" + an + "](),\n")
	})

	w.WriteString("\t)\n}\n")
	return w.String()
}

func (b *builder) fieldCall(typeName string, fd *ast.FieldDefinition, root bool) string {
	goRet := b.goType(fd.Type, "", false)
	if fb, ok := b.modelAnswers(typeName, fd); ok {
		return b.manifestFieldCall(typeName, fd, fb, goRet)
	}
	switch {
	case b.isSubscriptionRoot(typeName):
		meth := b.resolverMethod(typeName, fd.Name)
		if len(fd.Arguments) > 0 {
			an := b.argsName(typeName, fd.Name)
			return fmt.Sprintf("\t\t\tgraphql.SubscribeArgs(%q, func(ctx context.Context, a %s) (<-chan %s, error) { return r.%s(ctx, a) }),\n", fd.Name, an, goRet, meth)
		}
		return fmt.Sprintf("\t\t\tgraphql.Subscribe(%q, func(ctx context.Context) (<-chan %s, error) { return r.%s(ctx) }),\n", fd.Name, goRet, meth)
	case b.fieldKind(typeName, fd) == fieldPure:
		recv := "*" + b.modelRef(typeName, typeName)
		ident := goIdent(fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Field(%q, func(v %s) %s { return v.%s }),\n", fd.Name, recv, goRet, ident)
	case len(fd.Arguments) > 0 && root:
		an := b.argsName(typeName, fd.Name)
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.ResolveArgs(%q, func(ctx context.Context, _ graphql.Root, a %s) (%s, error) { return r.%s(ctx, a) }),\n", fd.Name, an, goRet, meth)
	case len(fd.Arguments) > 0:
		an := b.argsName(typeName, fd.Name)
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.ResolveArgs(%q, func(ctx context.Context, v *%s, a %s) (%s, error) { return r.%s(ctx, v, a) }),\n", fd.Name, b.modelRef(typeName, typeName), an, goRet, meth)
	case root:
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Resolve(%q, func(ctx context.Context, _ graphql.Root) (%s, error) { return r.%s(ctx) }),\n", fd.Name, goRet, meth)
	default:
		meth := b.resolverMethod(typeName, fd.Name)
		return fmt.Sprintf("\t\t\tgraphql.Resolve(%q, func(ctx context.Context, v *%s) (%s, error) { return r.%s(ctx, v) }),\n", fd.Name, b.modelRef(typeName, typeName), goRet, meth)
	}
}

func (b *builder) emitSchema() string {
	var w strings.Builder
	w.WriteString(b.header(b.pkgName, rootPkgDoc))
	w.WriteString(`import (
	"embed"

	"github.com/syssam/graphql-go"
)

//go:embed schema/*.graphql
var sdl embed.FS

func NewSchema(r Resolver, opts ...graphql.SchemaOption) (*graphql.Schema, error) {
	all := append([]graphql.SchemaOption{Bindings(r)}, opts...)
	return graphql.NewSchema(graphql.SDLFS(sdl, "schema/*.graphql"), all...)
}

// ValidateSchema builds the schema with no resolver behind it, so every
// binding error surfaces before a resolver is written. Building never calls a
// resolver -- Resolve captures it in a closure -- so the zero value is enough.
func ValidateSchema(opts ...graphql.SchemaOption) error {
	var r Resolver
	_, err := NewSchema(r, opts...)
	return err
}
`)
	return w.String()
}

// groupedNewSchemaDoc is written above the grouped NewSchema. Each group is
// registered the way a gRPC server registers a service, rather than through a
// struct with a field per group: a field left unset compiled, built, and
// failed on the first request to reach it, where a group left unregistered
// fails NewSchema with the fields it leaves unbound.
const groupedNewSchemaDoc = `// NewSchema builds the schema from the embedded SDL and the bindings given.
// Pass each group's bindings over its Resolver, as a gRPC server registers
// each service:
//
//	graph.NewSchema(user.Bindings(userResolver), post.Bindings(postResolver))
//
// A group that is not passed leaves its fields unbound, which NewSchema
// reports. Groups with no Resolver are included already.
`

func (b *builder) emitSchemaGrouped(groups []string) string {
	var w strings.Builder
	w.WriteString(b.header(b.pkgName, rootPkgDoc))
	w.WriteString("import (\n\t\"embed\"\n\n\t\"github.com/syssam/graphql-go\"\n")
	for _, g := range groups {
		w.WriteString("\t\"" + b.cfg.Package + "/" + g + "\"\n")
	}
	w.WriteString(")\n\n")
	w.WriteString("//go:embed schema/*.graphql\nvar sdl embed.FS\n\n")
	w.WriteString(groupedNewSchemaDoc)
	w.WriteString("func NewSchema(opts ...graphql.SchemaOption) (*graphql.Schema, error) {\n")
	w.WriteString("\tall := []graphql.SchemaOption{\n")
	for _, g := range groups {
		if !b.hasResolver(g) {
			w.WriteString("\t\t" + g + ".Bindings(),\n")
		}
	}
	w.WriteString("\t}\n")
	w.WriteString("\tall = append(all, opts...)\n")
	w.WriteString("\treturn graphql.NewSchema(graphql.SDLFS(sdl, \"schema/*.graphql\"), all...)\n}\n")
	w.WriteString(`
// ValidateSchema builds the schema with no resolver behind it, so every
// binding error surfaces before a resolver is written. Building never calls a
// resolver -- Resolve captures it in a closure -- so a nil one is enough.
func ValidateSchema(opts ...graphql.SchemaOption) error {
	all := []graphql.SchemaOption{
`)
	for _, g := range groups {
		if b.hasResolver(g) {
			w.WriteString("\t\t" + g + ".Bindings(nil),\n")
		}
	}
	w.WriteString("\t}\n")
	w.WriteString("\t_, err := NewSchema(append(all, opts...)...)\n\treturn err\n}\n")
	return w.String()
}

// emitGroup renders one group as a single file. Args, the Resolver interface
// and the bindings all live in the same package, so splitting them across
// three files only multiplied the file count: what the compiler rebuilds is
// decided by the package, not the file.
func (b *builder) emitGroup(pkg, group string, withResolver bool) string {
	parts := []string{b.emitArgs(group)}
	if withResolver {
		parts = append(parts, b.emitResolver(group))
	}
	parts = append(parts, b.emitBindings(group, withResolver))

	var body strings.Builder
	for _, p := range parts {
		if strings.TrimSpace(p) == "" {
			continue
		}
		body.WriteString(p)
		if !strings.HasSuffix(p, "\n\n") {
			body.WriteString("\n")
		}
	}
	s := body.String()
	if strings.TrimSpace(s) == "" {
		return ""
	}
	doc := ""
	if pkg != b.pkgName {
		doc = "holds the generated GraphQL bindings for the " + group + " group."
	}
	return b.header(pkg, doc) + b.importBlock(s, "") + s
}

// usedQualifiers reports which package qualifiers a generated body really
// refers to, by parsing it rather than by searching its text.
//
// A substring search cannot tell code from a comment, and the model file
// carries "bind it with graphql.Scalar in NewSchema options" above every
// custom scalar: on one real schema that alone imported the engine into a
// thousand packages that never used it, each one a compile error in a file
// marked DO NOT EDIT. A parse also ignores a qualifier inside a string
// literal, which a search does not.
//
// The body is Go with its imports not yet prepended, so it parses. If it ever
// does not, the search stays as the fallback: an import that is present and
// unused is a better failure than one that is missing.
func usedQualifiers(src string) func(string) bool {
	body := src
	if !strings.HasPrefix(strings.TrimLeft(body, " \t\r\n"), "package ") {
		body = "package p\n" + body
	}
	f, err := parser.ParseFile(token.NewFileSet(), "", body, parser.SkipObjectResolution)
	if err != nil {
		return func(q string) bool { return strings.Contains(src, q+".") }
	}
	seen := map[string]bool{}
	goast.Inspect(f, func(n goast.Node) bool {
		if sel, ok := n.(*goast.SelectorExpr); ok {
			if id, ok := sel.X.(*goast.Ident); ok {
				seen[id.Name] = true
			}
		}
		return true
	})
	return func(q string) bool { return seen[q] }
}

// reportUnboundScalars names every custom scalar the author still has to bind.
//
// A Models entry chooses the Go type; it does not register a marshaller, so a
// mapped scalar needs graphql.Scalar exactly as an unmapped one does. Believing
// otherwise is what made 21 641 of one real schema's build errors a surprise:
// Time was mapped to time.Time and still had no binding. The generator knows
// the whole list while it is generating, so it says so then rather than letting
// NewSchema say it later, once per use.
func (b *builder) reportUnboundScalars() {
	names := b.typeNames(ast.Scalar)
	if len(names) == 0 {
		return
	}
	parts := make([]string, 0, len(names))
	for _, name := range names {
		goType := "model." + name
		if expr, ok := b.cfg.Models[name]; ok {
			_, ref := splitModelExpr(expr)
			goType = ref
		}
		parts = append(parts, fmt.Sprintf("%s (%s)", name, goType))
	}
	b.notef("%d custom scalar(s) need a binding at NewSchema, or the schema will not build: %s. Add graphql.Scalar[GoType](%q, marshal, unmarshal) for each; a Models entry chooses the Go type but does not bind it.",
		len(parts), strings.Join(parts, ", "), names[0])
}
