// The generated package embeds every schema/*.graphql it holds, so an SDL
// file removed from the sources must leave the output too, or its types stay
// in the served schema.
func TestDeletedSDLLeavesTheEmbeddedSchema(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) {
		p := filepath.Join(dir, "sdl", name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("query.graphql", "type Query { ping: Boolean }\n")
	write("legacy.graphql", "type Legacy { id: ID! }\nextend type Query { legacy: Legacy }\n")
	gen := func() {
		t.Helper()
		if err := Generate(context.Background(), Config{Dir: dir, SchemaGlobs: []string{"sdl/*.graphql"}, Output: "graph", Package: "hello/graph"}); err != nil {
			t.Fatal(err)
		}
	}
	gen()
	copyOf := filepath.Join(dir, "graph", "schema", "legacy.graphql")
	if _, err := os.Stat(copyOf); err != nil {
		t.Fatalf("the first run should embed legacy.graphql: %v", err)
	}

	if err := os.Remove(filepath.Join(dir, "sdl", "legacy.graphql")); err != nil {
		t.Fatal(err)
	}
	gen()
	if _, err := os.Stat(copyOf); !os.IsNotExist(err) {
		t.Errorf("legacy.graphql was deleted from the sources but is still embedded (stat err %v)", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "graph", "schema", "query.graphql")); err != nil {
		t.Errorf("a file still in the sources was removed: %v", err)
	}
}

// A group whose types all left its SDL, or became bound to Go types of their
// own, stops getting a models.go. The old one must go with it: it still
// compiles, so nothing reports it, and it declares types no binding uses.
func TestStaleGeneratedFilesAreRemoved(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, body string) {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("sdl/query.graphql", "type Query { ping: Boolean }\n")
	write("sdl/legacy.graphql", "input LegacyOrder { by: String }\nextend type Query { legacy(order: LegacyOrder): Boolean }\n")
	gen := func() {
		t.Helper()
		if err := Generate(context.Background(), Config{Dir: dir, SchemaGlobs: []string{"sdl/*.graphql"}, Output: "graph", Package: "hello/graph"}); err != nil {
			t.Fatal(err)
		}
	}
	gen()
	stale := filepath.Join(dir, "graph", "model", "legacy", "models.go")
	src, err := os.ReadFile(stale)
	if err != nil {
		t.Fatalf("the first run should write the legacy group's models: %v", err)
	}
	// As a checkout with core.autocrlf leaves it: the header still marks it.
	write("graph/model/legacy/models.go", strings.ReplaceAll(string(src), "\n", "\r\n"))
	// Files the generator does not own sit beside its output and must survive.
	handWritten := filepath.Join(dir, "graph", "legacy", "extra.go")
	write("graph/legacy/extra.go", "package legacy\n")
	notOurs := filepath.Join(dir, "graph", "model", "other", "models.go")
	write("graph/model/other/models.go", "// Code generated by someone else. DO NOT EDIT.\n\npackage other\n")
	// Another gqlc run's output nested in this one's: its files carry the same
	// header and this run wrote none of them.
	nested := filepath.Join(dir, "graph", "admin", "schema.go")
	write("graph/admin/schema.go", "// Code generated by gqlc. DO NOT EDIT.\n\npackage admin\n")
	write("graph/admin/schema/admin.graphql", "type Query { admin: Boolean }\n")
	// Directories the go command ignores hold fixtures, not stale output: a
	// golden copy of gqlc's output carries its header and must survive.
	var ignored []string
	for _, d := range []string{"testdata", "vendor", ".cache", "_old"} {
		p := filepath.Join(dir, "graph", d, "golden", "generated.go")
		write(filepath.ToSlash(filepath.Join("graph", d, "golden", "generated.go")), "// Code generated by gqlc. DO NOT EDIT.\n\npackage golden\n")
		ignored = append(ignored, p)
	}
	// A group's own hand-written schema/ directory does not make it another
	// gqlc root: its stale generated.go must still go.
	write("graph/legacy/schema/validate.json", "{}\n")

	if err := os.Remove(filepath.Join(dir, "sdl", "legacy.graphql")); err != nil {
		t.Fatal(err)
	}
	gen()
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Errorf("legacy's models.go outlived its SDL (stat err %v)", err)
	}
	if _, err := os.Stat(filepath.Dir(stale)); !os.IsNotExist(err) {
		t.Errorf("the emptied model/legacy directory was left behind (stat err %v)", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "graph", "legacy", "generated.go")); !os.IsNotExist(err) {
		t.Errorf("legacy's generated.go outlived its SDL (stat err %v)", err)
	}
	for _, keep := range append([]string{handWritten, notOurs, nested, filepath.Join(dir, "graph", "schema.go")}, ignored...) {
		if _, err := os.Stat(keep); err != nil {
			t.Errorf("%s is not stale and was removed: %v", keep, err)
		}
	}
}
