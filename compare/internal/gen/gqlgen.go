// writeGqlgen configures gqlgen to bind the shared structs and to resolve
// every composite field, runs its generator, then writes a ResolverRoot over
// the shared dataset. gqlgen's own resolver stub generation is left off, so
// there are no panic bodies to patch.
func writeGqlgen(root string, n int) error {
	// Clear the tree first, for the same reason as graphqlgo: a smaller run
	// must not inherit the previous one's generated packages.
	if err := os.RemoveAll(filepath.Join(root, "gqlgen", "gen")); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(root, "gqlgen", "gen", "gqlgen.yml"), gqlgenConfig(n)); err != nil {
		return err
	}
	cfg, err := config.LoadConfig(filepath.Join(root, "gqlgen", "gen", "gqlgen.yml"))
	if err != nil {
		return fmt.Errorf("load config: %w", err)
	}
	if err := api.Generate(cfg); err != nil {
		return fmt.Errorf("generate: %w", err)
	}
	return writeFile(filepath.Join(root, "gqlgen", "gen", "resolvers.go"), gqlgenResolvers(n))
}

func gqlgenConfig(n int) string {
	var b strings.Builder
	fmt.Fprintf(&b, `# Code generated by compare/internal/gen. DO NOT EDIT.
# skip_mod_tidy: the module imports the packages this run generates, so a
# tidy before they exist fails.
skip_mod_tidy: true
schema:
  - schema/*.graphql
exec:
  filename: gqlgen/gen/exec/generated.go
  package: exec
model:
  filename: gqlgen/gen/exec/model/models_gen.go
  package: model
models:
  PageInfo:
    model: %[1]s/shared.PageInfo
`, ModulePath)

	for i := range n {
		name := EntityName(i)
		fmt.Fprintf(&b, `  %[2]s:
    model: %[1]s/shared.%[2]s
    fields:
      owner: { resolver: true }
      children: { resolver: true }
  %[2]sConnection:
    model: %[1]s/shared.%[2]sConnection
    fields:
      edges: { resolver: true }
      pageInfo: { resolver: true }
  %[2]sEdge:
    model: %[1]s/shared.%[2]sEdge
    fields:
      node: { resolver: true }
`, ModulePath, name)
	}
	return b.String()
}

func gqlgenResolvers(n int) string {
	var b strings.Builder
	b.WriteString(header("gen"))
	fmt.Fprintf(&b, `import (
	"context"

	"%[1]s/gqlgen/gen/exec"
	"%[1]s/gqlgen/gen/exec/model"
	"%[1]s/shared"
)

// Resolver implements exec.ResolverRoot over the shared dataset.
type Resolver struct{}

func (r *Resolver) Query() exec.QueryResolver       { return queryResolver{} }
func (r *Resolver) Mutation() exec.MutationResolver { return mutationResolver{} }

type queryResolver struct{}
type mutationResolver struct{}

func first(v *int) int {
	if v == nil {
		return 0
	}
	return *v
}

func (mutationResolver) Ping(_ context.Context) (bool, error) { return true, nil }
`, ModulePath)

	for i := range n {
		name := EntityName(i)
		owner := EntityName((i + 1) % n)
		child := EntityName((i + 2) % n)
		lower := lowerFirst(name)

		fmt.Fprintf(&b, `
type %[1]sResolver struct{}
type %[1]sConnectionResolver struct{}
type %[1]sEdgeResolver struct{}

func (r *Resolver) %[1]s() exec.%[1]sResolver { return %[1]sResolver{} }
func (r *Resolver) %[1]sConnection() exec.%[1]sConnectionResolver {
	return %[1]sConnectionResolver{}
}
func (r *Resolver) %[1]sEdge() exec.%[1]sEdgeResolver { return %[1]sEdgeResolver{} }

func (%[1]sResolver) Owner(_ context.Context, obj *shared.%[1]s) (*shared.%[2]s, error) {
	return shared.Owner%[1]s(obj), nil
}

func (%[1]sResolver) Children(_ context.Context, obj *shared.%[1]s, f *int, _ *string, _ *int, _ *string, _ *model.%[3]sWhereInput, _ *model.%[3]sOrder) (*shared.%[3]sConnection, error) {
	return shared.Children%[1]s(obj, first(f)), nil
}

func (%[1]sConnectionResolver) Edges(_ context.Context, obj *shared.%[1]sConnection) ([]*shared.%[1]sEdge, error) {
	return shared.Edges%[1]s(obj), nil
}

func (%[1]sConnectionResolver) PageInfo(_ context.Context, obj *shared.%[1]sConnection) (*shared.PageInfo, error) {
	return shared.PageInfo%[1]s(obj), nil
}

func (%[1]sEdgeResolver) Node(_ context.Context, obj *shared.%[1]sEdge) (*shared.%[1]s, error) {
	return obj.Node, nil
}

func (queryResolver) %[1]s(_ context.Context, id string) (*shared.%[1]s, error) {
	return shared.Get%[1]s(id), nil
}

func (queryResolver) %[1]ss(_ context.Context, f *int, _ *string, _ *int, _ *string, _ *model.%[1]sWhereInput, _ *model.%[1]sOrder) (*shared.%[1]sConnection, error) {
	return shared.Conn%[1]s(first(f)), nil
}

func (mutationResolver) Create%[1]s(_ context.Context, input model.Create%[1]sInput) (*shared.%[1]s, error) {
	v := *shared.List%[1]s()[0]
	v.Name = input.Name
	return &v, nil
}

func (mutationResolver) Update%[1]s(_ context.Context, id string, input model.Update%[1]sInput) (*shared.%[1]s, error) {
	src := shared.Get%[1]s(id)
	if src == nil {
		return nil, nil
	}
	v := *src
	if input.Name != nil {
		v.Name = *input.Name
	}
	return &v, nil
}

func (mutationResolver) Delete%[1]s(_ context.Context, id string) (bool, error) {
	return shared.Get%[1]s(id) != nil, nil
}
`, name, owner, child, lower)
	}

	// Query.node returns the first entity, which is enough to exercise the
	// interface path without depending on which entity an id belongs to.
	fmt.Fprintf(&b, `
func (queryResolver) Node(_ context.Context, id string) (model.Node, error) {
	if v := shared.Get%[1]s(id); v != nil {
		return v, nil
	}
	return nil, nil
}
`, EntityName(0))

	return b.String()
}

