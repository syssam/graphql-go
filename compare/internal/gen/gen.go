// ModulePath is the import path of the comparison module.
const ModulePath = "github.com/syssam/graphql-go/compare"

// Generate writes the shared schema and structs, then each engine's config,
// generated code and resolvers, for n entities.
func Generate(root string, n int) error {
	if n < 2 {
		return fmt.Errorf("gen: need at least 2 entities, got %d", n)
	}
	steps := []struct {
		name string
		fn   func(string, int) error
	}{
		{"schema", writeSchema},
		{"shared", writeShared},
		{"gqlgen", writeGqlgen},
		{"graphqlgo", writeGraphQLGo},
	}
	for _, s := range steps {
		if err := s.fn(root, n); err != nil {
			return fmt.Errorf("gen %s: %w", s.name, err)
		}
	}
	return nil
}

// writeSchema lays the SDL out one file per entity, which is the layout the
// per-group split in gqlc is designed for and which gqlgen ignores.
func writeSchema(root string, n int) error {
	dir := filepath.Join(root, "schema")
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, body := range buildbench.SDLFiles(n) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// objectTypes lists the GraphQL object types bound to the shared package.
// Input objects and enums stay engine-generated: they are decode-only, and
// binding them would not change what a query costs to execute.
func objectTypes(n int) []string {
	out := []string{"PageInfo"}
	for i := range n {
		name := EntityName(i)
		out = append(out, name, name+"Connection", name+"Edge")
	}
	return out
}

func writeFile(path, body string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

func header(pkg string) string {
	return "// Code generated by compare/internal/gen. DO NOT EDIT.\n\npackage " + pkg + "\n\n"
}

func indentJoin(lines []string) string { return strings.Join(lines, "\n") }
